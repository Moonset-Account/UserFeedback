"""Runnable header-dependency pruning demonstration.

Scenario
--------
1. A generator creates ``build/config.h`` and a synthetic compiler includes it,
   so the first successful compile records that dynamic edge.
2. The generator rewrites the header and ``src/main.c`` is changed so the
   compiler no longer includes the header.  The old edge orders the generator
   first; the successful recompilation replaces the manifest with no header edge.
3. The generator rewrites the header again.  Only the generator reruns; the
   compiler remains cached because its new manifest no longer reads the header.
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .coordinator import BuildCoordinator

INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.MULTILINE)

INITIAL_SOURCE = '''#include "config.h"

int main(void) {
    return FEATURE;
}
'''

NO_INCLUDE_SOURCE = """int main(void) {
    return 0;
}
"""

INITIAL_TEMPLATE = "#define FEATURE 1\n"
SECOND_TEMPLATE = "#define FEATURE 2\n"
THIRD_TEMPLATE = "#define FEATURE 3\n"


def _compiler_action(ctx: Any) -> None:
    source = ctx.read_text("src/main.c")
    read_headers: list[str] = []

    for header in INCLUDE_RE.findall(source):
        for include_dir in ("src", "build"):
            candidate = f"{include_dir}/{header}"
            if ctx.exists(candidate):
                ctx.read(candidate)
                read_headers.append(candidate)
                break
        else:
            raise FileNotFoundError(f"included header not found: {header}")

    # Synthetic object bytes incorporate every actually read input.
    fingerprint_input = source + "\n".join(
        record.path + record.version.token for record in ctx.reads
    )
    ctx.write_output(
        "build/main.o",
        "SYNTHETIC_OBJECT\n"
        f"reads={','.join(read_headers) or '<none>'}\n"
        f"fingerprint={fingerprint_input.__len__()}\n",
    )


def _generator_action(ctx: Any) -> None:
    template = ctx.read_text("templates/config.h.in")
    ctx.write_output(
        "build/config.h",
        "/* generated by generate_header; do not edit */\n" + template,
    )


@dataclass
class HeaderDemoReport:
    coordinator: BuildCoordinator
    first: Any
    second: Any
    third: Any

    def summary(self) -> list[str]:
        def line(label: str, result: Any) -> str:
            ran = ", ".join(result.ran_steps) or "-"
            cached = ", ".join(result.cached_steps) or "-"
            failed = ", ".join(result.failed_steps) or "-"
            return (
                f"{label}: ran=[{ran}] cached=[{cached}] failed=[{failed}]"
            )

        first_manifest = self.coordinator.dynamic_dependencies("compile")
        # Manifest after all three builds is the pruned one.  Capture second via
        # result view where needed by callers/tests.
        return [
            line("build 1", self.first),
            line("build 2", self.second),
            line("build 3", self.third),
            "final compile dynamic deps: "
            + (", ".join(sorted(first_manifest)) or "<none>"),
        ]


def run_header_demo(root: str | Path) -> HeaderDemoReport:
    """Create synthetic files under ``root`` and run the three-build demo."""

    root_path = Path(root)
    root_path.mkdir(parents=True, exist_ok=True)
    coordinator = BuildCoordinator(root=root_path)

    coordinator.write_file("templates/config.h.in", INITIAL_TEMPLATE)
    coordinator.write_file("src/main.c", INITIAL_SOURCE)

    coordinator.add_step(
        "generate_header",
        _generator_action,
        outputs=["build/config.h"],
        static_dependencies=["templates/config.h.in"],
    )
    coordinator.add_step(
        "compile",
        _compiler_action,
        outputs=["build/main.o"],
        static_dependencies=["src/main.c"],
    )

    first = coordinator.run()
    first.raise_for_status()
    first_manifest = coordinator.dynamic_dependencies("compile")
    if "build/config.h" not in first_manifest:
        raise AssertionError("first compile should record build/config.h")

    # Both the header template and source change.  The old dynamic edge still
    # forces generate_header before compile in this second build.
    coordinator.write_file("templates/config.h.in", SECOND_TEMPLATE)
    coordinator.write_file("src/main.c", NO_INCLUDE_SOURCE)
    second = coordinator.run()
    second.raise_for_status()
    second_manifest = coordinator.dynamic_dependencies("compile")
    if "build/config.h" in second_manifest:
        raise AssertionError(
            "second compile should prune build/config.h, got "
            f"{sorted(second_manifest)}"
        )

    # The header changes again, but compile's committed manifest no longer has
    # an edge or version entry for it.
    coordinator.write_file("templates/config.h.in", THIRD_TEMPLATE)
    third = coordinator.run()
    third.raise_for_status()

    return HeaderDemoReport(coordinator, first, second, third)


def main() -> None:
    workspace_demo = Path.cwd() / "demo-workspace"
    if workspace_demo.exists():
        shutil.rmtree(workspace_demo)
    report = run_header_demo(workspace_demo)

    print("Incremental build header-pruning demo")
    print("synthetic workspace: ./demo-workspace")
    print()
    print("Build 1: generator creates config.h; compile includes it")
    for step in report.first.steps:
        print(f"  - {step.name}: {step.status} ({step.reason})")
    print(
        "  compile dynamic deps after build 1: "
        + ", ".join(report.first.step("compile").dynamic_dependencies)
    )

    print()
    print("Build 2: generator rewrites header; compile no longer includes it")
    for step in report.second.steps:
        attempts = f", attempts={step.attempt_count}" if step.retried else ""
        print(f"  - {step.name}: {step.status} ({step.reason}{attempts})")
    print(
        "  compile dynamic deps after build 2: "
        + (", ".join(report.second.step("compile").dynamic_dependencies) or "<none>")
    )

    print()
    print("Build 3: generator rewrites header again")
    for step in report.third.steps:
        print(f"  - {step.name}: {step.status} ({step.reason})")
    print("  => generate_header reruns; compile does not rerun.")
    print()
    for line in report.summary():
        print(line)


if __name__ == "__main__":
    main()
