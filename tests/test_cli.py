"""Command-line behaviour on a small synthetic metadata file."""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

METADATA = {
    "images": [
        {
            "image_id": "pass1.img",
            "device_identity": "DEV-A",
            "capture_id": "CAP-1",
            "segment_size": 512,
            "segments": [
                {"index": 0, "status": "read", "digest": "h0"},
                {"index": 1, "status": "unreadable", "fill_byte": 0},
            ],
        },
        {
            "image_id": "pass2.img",
            "device_identity": "DEV-B",
            "capture_id": "CAP-2",
            "segment_size": 512,
            "segments": [
                {"index": 0, "status": "read", "digest": "h0"},
                {"index": 1, "status": "read", "digest": "h1"},
            ],
        },
    ]
}


def run_cli(*args: str) -> subprocess.CompletedProcess:
    # The package lives in ROOT, so it must be importable; the metadata written
    # here is synthetic and generated by this test.
    return subprocess.run(
        [sys.executable, "-m", "forensic_segments", *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


class CommandLineTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.meta = Path(self.tmp.name) / "meta.json"
        self.meta.write_text(json.dumps(METADATA), encoding="utf-8")

    def test_text_report(self):
        result = run_cli(str(self.meta), "--start", "0", "--end", "1024")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("[512, 1024)", result.stdout)
        self.assertIn("pass2.img", result.stdout)
        self.assertIn("Missing 0", result.stdout)

    def test_json_output(self):
        result = run_cli(str(self.meta), "--start", "0", "--end", "1024", "--json")
        self.assertEqual(result.returncode, 0, result.stderr)
        payload = json.loads(result.stdout)
        self.assertEqual(payload["segments"][1]["image_id"], "pass2.img")
        self.assertEqual(payload["segments"][1]["file_offset"], 512)
        self.assertTrue(payload["summary"]["is_complete"])

    def test_prefer_is_honoured(self):
        result = run_cli(
            str(self.meta), "--start", "0", "--end", "512", "--prefer", "pass2.img", "--json"
        )
        payload = json.loads(result.stdout)
        self.assertEqual(payload["segments"][0]["image_id"], "pass2.img")

    def test_bad_range_returns_error(self):
        result = run_cli(str(self.meta), "--start", "100", "--end", "50")
        self.assertEqual(result.returncode, 2)
        self.assertIn("error:", result.stderr)

    def test_missing_file_returns_error(self):
        result = run_cli(str(Path(self.tmp.name) / "nope.json"), "--start", "0", "--end", "1")
        self.assertEqual(result.returncode, 2)
        self.assertIn("error:", result.stderr)

    def test_invalid_metadata_returns_error(self):
        bad = Path(self.tmp.name) / "bad.json"
        bad.write_text(json.dumps({"images": [{"image_id": "x.img"}]}), encoding="utf-8")
        result = run_cli(str(bad), "--start", "0", "--end", "1")
        self.assertEqual(result.returncode, 2)
        self.assertIn("missing keys", result.stderr)


if __name__ == "__main__":
    unittest.main()
